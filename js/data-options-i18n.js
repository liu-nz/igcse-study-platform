// 双向索引：中文 ↔ English（以及原始混排串 → 拆分后的中英对照）
const OPTION_I18N = (() => {
    const map = Object.create(null);
    const put = (key, pair) => { if (key && !map[key]) map[key] = pair; };
    OPTION_I18N_PAIRS.forEach(row => {
        const zh = row[0];
        const en = row[1];
        const mixed = row[2];
        const pair = { zh, en };
        put(zh, pair);
        put(en, pair);
        if (mixed) put(mixed, pair);
    });
    return map;
})();

// 英语科目保持原样；语言中立的选项返回 null，按原文本单行显示
function optionPair(text, subject) {
    if (!text || subject === '英语') return null;
    const key = String(text).trim();
    const hit = OPTION_I18N[key];
    if (!hit || hit.zh === hit.en) return null;
    return hit;
}

// 把选项渲染成「中文 + 英文」两行；无对照时原样输出
function optionHtml(text, subject) {
    const pair = optionPair(text, subject);
    if (!pair) return escapeHtml(String(text));
    return `<span class="opt-zh">${escapeHtml(pair.zh)}</span><span class="opt-en">${escapeHtml(pair.en)}</span>`;
}

// 一行式对照（用于「正确答案」「错题本」等位置）：范围校验（Range check）
function optionInline(text, subject) {
    const pair = optionPair(text, subject);
    if (!pair) return escapeHtml(String(text));
    return `${escapeHtml(pair.zh)}<span class="opt-en-inline">（${escapeHtml(pair.en)}）</span>`;
}
